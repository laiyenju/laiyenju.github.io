// Builds assets/js/pixel-engine.js from the vendored Pixel Plays engine (assets/vendor/pixel-plays/engine.js).
// The original runs one scene on one <canvas id="c">; this wraps it in createPixelEngine(canvas, SCENE)
// so the homepage can keep several scenes, and adds what the site needs: a canvas size and scale per scene,
// a turn around the scene centre, and boxes that paint every side facing the camera.
// Run: node scripts/pixel-engine/build.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '..');
let eng = fs.readFileSync(path.join(root, 'assets/vendor/pixel-plays/engine.js'), 'utf8');
const must = (from, to) => { if (!eng.includes(from)) throw new Error('engine changed, not found: ' + from.slice(0, 60)); eng = eng.replace(from, to); };
must("'use strict';", '');
must('const SCENE = window.PP_SCENE || {};', '');
must("const canvas = document.getElementById('c');", '');
must('const OX = W / 2,', 'const OX = W / 2 + (SCENE.originX || 0),');
must('const W = 360, H = 280, S = 10;', 'const W = SCENE.W || 360, H = SCENE.H || 280, S = SCENE.S || 10;\nconst ROT = SCENE.rot || 0, RC = Math.cos(ROT), RS = Math.sin(ROT), CX = SCENE.cx || 0, CY = SCENE.cy || 0;');
must(`function project(x, y, z) {
  const u = (x - y) / R2, v = (x + y) / R2;`, `function project(x, y, z) {
  const dx = x - CX, dy = y - CY, rx = dx * RC - dy * RS, ry = dx * RS + dy * RC;
  const u = (rx - ry) / R2, v = (rx + ry) / R2;`);
must(`  return { x: (u + v) / R2, y: (v - u) / R2 };`, `  const rx = (u + v) / R2, ry = (v - u) / R2;
  return { x: CX + rx * RC + ry * RS, y: CY - rx * RS + ry * RC };`);
const b0 = eng.indexOf('function box('), b1 = eng.indexOf('function castShadow(');
if (b0 < 0 || b1 < 0) throw new Error('engine changed: box() not found');
eng = eng.slice(0, b0) + `function box(x0, y0, z0, x1, y1, z1, c, seed = 0) {
  const ramp = rampOf(c);
  const paint = (x, y, z, base, grain) => {
    const p = project(x, y, z), ix = p.sx | 0, iy = p.sy | 0;
    if (ix < 0 || iy < 0 || ix >= W || iy >= H) return;
    const i = iy * W + ix;
    if (p.d <= zb[i]) return;
    zb[i] = p.d;
    pix[i] = ramp[clamp(Math.floor(base + (grain - .5) * 1.3 + (bayerAt(ix, iy) - .5) * .5), 0, 4)];
  };
  const step = .045, longX = x1 - x0 >= y1 - y0;
  for (let a = x0; a <= x1; a += step) for (let b = y0; b <= y1; b += step) {
    paint(a, b, z1, 3.4, longX ? noise(a * .8 + seed, b * 9) : noise(a * 9, b * .8 + seed));
  }
  const faces = [[0, 1, 'y', y1], [0, -1, 'y', y0], [1, 0, 'x', x1], [-1, 0, 'x', x0]];
  for (const [nx, ny, axis, at] of faces) {
    const rnx = nx * RC - ny * RS, rny = nx * RS + ny * RC;
    if (rnx + rny <= .01) continue;
    const base = 1.75 - .55 * (rnx - rny);
    if (axis === 'y') { for (let a = x0; a <= x1; a += step) for (let b = z0; b <= z1; b += step) paint(a, at, b, base, noise(a * .8 + seed, b * 9)); }
    else { for (let a = y0; a <= y1; a += step) for (let b = z0; b <= z1; b += step) paint(at, a, b, base, noise(a * .8 + seed, b * 9)); }
  }
}
` + eng.slice(b1);
const exportsList = 'W,H,S,R2,COS,SIN,rgb,rampOf,bayerAt,tint,clamp,lerp,hash,noise,project,unproject,sphere,capsule,box,castShadow,applyShadows,shadeEdges,kinds,KIND_GRASS,growGrass,drawTufts,drawLeaves,bakeOcclusion,plot,growTree,figure,dynamicAdd,pendingShadows,flushShadows,pix,zb,bakedPix,bakedZ,ground,groundZ,shadowMask,staticShadow,ctx,image,STILL,GRASS';
const out = `/* Generated by scripts/pixel-engine/build.js — do not edit by hand.
   Pixel Plays engine, MIT License, Copyright (c) 2026 Amir Mushich (assets/vendor/pixel-plays/LICENSE).
   https://github.com/amirmushichge/pixel-plays */
function createPixelEngine(canvas, SCENE) {
'use strict';
${eng}
return { ${exportsList} };
}
`;
fs.writeFileSync(path.join(root, 'assets/js/pixel-engine.js'), out);
console.log('wrote assets/js/pixel-engine.js', out.length, 'bytes');
